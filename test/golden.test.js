/**
 * M2's golden-render criterion, and M8's "exported pages match the intended layout".
 *
 * The fixture is a **hash**, not a screenshot: the renderer is deterministic, so a change in
 * layout, lettering or the order objects are drawn changes the bytes and fails the test. The
 * test also proves the hash is not vacuous by breaking a panel border and watching it change.
 *
 * `UPDATE_GOLDEN=1 node --test test/golden.test.js` rewrites the fixture deliberately; CI
 * never sets it.
 * @module test/golden
 */

import { test } from 'node:test';
import { must, sessionHarness } from './helpers.js';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pageToPng, pngSize } from '../server/export/png.js';
import { pageToSvg } from '../server/export/svg.js';

const FIXTURE = join(import.meta.dirname, 'fixtures', 'golden-representative.json');

/**
 * A page that exercises the things that can silently change: a grid with gutters, artwork,
 * every lettering presentation, a tail, and a sound effect in the display face.
 * @param {any} session
 */
async function representativePage(session) {
  must(await session.run('comic.project.create', { title: 'Golden Representative' }));
  const page = must(await session.run('comic.page.add', { name: 'Page 1', template: 'three-by-two' }));
  const panels = session.bundle.project.pages[page.pageId].panelIds;

  for (let i = 0; i < panels.length; i++) {
    must(await session.run('comic.artwork.place', {
      panelId: panels[i], name: `Art ${i + 1}`, contentHash: `golden-${i + 1}`,
    }));
    must(await session.run('comic.artwork.clip', { panelId: panels[i], inset: 6 }));
  }

  must(await session.run('comic.lettering.add', {
    panelId: panels[0], kind: 'balloon', variant: 'speech', text: 'THE CITY IS QUIET TONIGHT.',
    x: 60, y: 80, width: 300, height: 90, overflowPolicy: 'shrink', tailToX: 140, tailToY: 240,
  }));
  must(await session.run('comic.lettering.add', {
    panelId: panels[1], kind: 'balloon', variant: 'thought', text: 'TOO QUIET.',
    x: 420, y: 120, width: 220, height: 80, overflowPolicy: 'shrink',
  }));
  must(await session.run('comic.lettering.add', {
    panelId: panels[2], kind: 'caption', text: 'A SHADOW MOVES BEHIND HER.',
    x: 720, y: 70, width: 380, height: 70, overflowPolicy: 'warn',
  }));
  must(await session.run('comic.lettering.add', {
    panelId: panels[3], kind: 'balloon', variant: 'shout', text: 'LOOK OUT!',
    x: 80, y: 900, width: 260, height: 80, overflowPolicy: 'shrink',
  }));
  must(await session.run('comic.lettering.add', {
    panelId: panels[4], kind: 'balloon', variant: 'whisper', text: 'who is there?',
    x: 440, y: 1000, width: 260, height: 70, overflowPolicy: 'shrink',
  }));
  must(await session.run('comic.lettering.add', {
    panelId: panels[5], kind: 'sound-effect', text: 'KRAKOOM!',
    x: 780, y: 1050, width: 380, height: 140, overflowPolicy: 'shrink',
  }));
  return page.pageId;
}

/** @param {any} bundle @param {string} pageId */
function render(bundle, pageId) {
  const page = bundle.project.pages[pageId];
  const png = pageToPng(bundle, page, 0.5);
  const svg = pageToSvg(bundle, page);
  return {
    png,
    svg,
    pngHash: createHash('sha256').update(png).digest('hex'),
    svgHash: createHash('sha256').update(svg).digest('hex'),
  };
}

test('the representative page renders byte-identically to its golden fixture', async (t) => {
  const session = sessionHarness(t);
  const pageId = await representativePage(session);
  const first = render(session.bundle, pageId);
  const second = render(session.bundle, pageId);
  assert.equal(first.pngHash, second.pngHash, 'the PNG renderer is deterministic');
  assert.equal(first.svgHash, second.svgHash, 'the SVG renderer is deterministic');

  const size = await pngSize(first.png);
  let expected;
  try {
    expected = JSON.parse(await readFile(FIXTURE, 'utf8'));
  } catch {
    expected = null;
  }
  if (!expected || process.env.UPDATE_GOLDEN === '1') {
    await writeFile(FIXTURE, `${JSON.stringify({
      note: 'Generated by test/golden.test.js. UPDATE_GOLDEN=1 rewrites it deliberately.',
      pngHash: first.pngHash,
      svgHash: first.svgHash,
      width: size.width,
      height: size.height,
    }, null, 2)}\n`, 'utf8');
    t.diagnostic('golden fixture written');
    return;
  }

  assert.equal(first.pngHash, expected.pngHash,
    'the representative page changed; inspect the diff, then UPDATE_GOLDEN=1 if it is intended');
  assert.equal(first.svgHash, expected.svgHash);
  assert.deepEqual(size, { width: expected.width, height: expected.height });
});

test('the golden fixture is not vacuous: removing a panel border changes the render', async (t) => {
  const session = sessionHarness(t);
  const pageId = await representativePage(session);
  const before = render(session.bundle, pageId);

  const panelId = session.bundle.project.pages[pageId].panelIds[0];
  const frameNodeId = session.bundle.project.panels[panelId].frameNodeId;
  session.bundle.document.nodes[String(frameNodeId)].stroke = null;
  const after = render(session.bundle, pageId);
  assert.notEqual(after.pngHash, before.pngHash, 'a missing border is visible to the test');
  assert.notEqual(after.svgHash, before.svgHash);
});
